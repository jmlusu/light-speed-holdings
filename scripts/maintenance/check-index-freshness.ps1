#Requires -Version 5.1
<#
.SYNOPSIS
  INDEX.json byte-freshness guard: reindex under Windows PowerShell 5.1 (the
  canonical ConvertTo-Json dialect) and fail if harness/changes/INDEX.json
  differs from the regenerated bytes.

.DESCRIPTION
  lint-ecl.ps1's INDEX check is semantic (parse + property compare) and blind
  to byte-level drift: EOL, indent width, ": " spacing, unicode escaping.
  This script closes that gap for CI (.github/workflows/ci.yml, job
  "INDEX.json Freshness Check") and pre-commit (.pre-commit-config.yaml, hook
  "index-freshness").

  Regeneration runs harness-change.ps1 as a child powershell.exe process with
  CWD = repo root (its paths are CWD-relative), byte-equivalent to the
  documented fix command:
    powershell -NoProfile -ExecutionPolicy Bypass -File scripts/maintenance/harness-change.ps1 reindex

  Note: `reindex` also runs the harness auto-evolve check. With
  harness/evolution/pending.md present that check only prints a reminder; the
  same side effect as the documented manual command.

.NOTES
  Must run under Windows PowerShell 5.1: pwsh 7's ConvertTo-Json emits a
  different dialect (2-space indent, single space after ':', literal '&'),
  which would report false drift. The guard below enforces this.
#>
$ErrorActionPreference = 'Stop'

if ($PSVersionTable.PSEdition -ne 'Desktop' -or $PSVersionTable.PSVersion.Major -ne 5) {
  Write-Output "FAIL: run this check under Windows PowerShell 5.1 (powershell.exe), not $($PSVersionTable.PSVersion) ($($PSVersionTable.PSEdition))."
  Write-Output "      ConvertTo-Json output differs across PowerShell versions; checking under pwsh would report false drift."
  exit 1
}

$repoRoot = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\..'))
$indexRelPath = 'harness/changes/INDEX.json'
$changeScript = Join-Path $repoRoot 'scripts\maintenance\harness-change.ps1'

Push-Location -LiteralPath $repoRoot
try {
  & powershell -NoProfile -ExecutionPolicy Bypass -File $changeScript reindex
  if ($LASTEXITCODE -ne 0) {
    Write-Output "FAIL: harness-change.ps1 reindex exited with code $LASTEXITCODE."
    exit 1
  }

  git diff --exit-code -- $indexRelPath
  if ($LASTEXITCODE -ne 0) {
    Write-Output ""
    Write-Output "FAIL: $indexRelPath is not byte-fresh (diff above: committed vs regenerated under Windows PowerShell 5.1)."
    Write-Output "      Fix: powershell -NoProfile -ExecutionPolicy Bypass -File scripts/maintenance/harness-change.ps1 reindex"
    Write-Output "      Then: git add harness/changes/INDEX.json"
    exit 1
  }

  Write-Output "OK: $indexRelPath is byte-fresh (regenerated under Windows PowerShell 5.1, no drift)."
  exit 0
}
finally {
  Pop-Location
}
