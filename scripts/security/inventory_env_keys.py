"""Generate a .env key inventory — NAMES ONLY (F-04 credential rotation runbook support).

Lists which files exist and which variable NAMES each defines. Values are
never printed, logged, or included in the output (neither directly nor
encoded). "set" is a boolean only (non-empty, non-placeholder value seen);
no lengths, no hashes, no prefixes are emitted.

Usage:
    uv run python scripts/security/inventory_env_keys.py [--output reports/env-inventory-2026-11-08.md]
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

_KEY_LINE = re.compile(r"^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$", re.IGNORECASE)

_PLACEHOLDERS = (
    # NOTE: the empty-value case is handled by the `stripped == ""` check
    # above — an empty string here would match EVERY value (startswith("")).
    "changeme",
    "placeholder",
    "your-",
    "example",
    "xxx",
    "todo",
    "replace-",
)


def looks_placeholder(value: str) -> bool:
    """Heuristic: name-like empty/placeholder values only (value not emitted)."""
    stripped = value.strip().strip('"').strip("'").strip()
    if stripped == "":
        return True
    lowered = stripped.lower()
    return any(lowered.startswith(p) for p in _PLACEHOLDERS)


def parse_env_file(path: Path) -> list[tuple[str, bool]]:
    """Return [(key_name, is_set)] for a .env-style file. Values discarded."""
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return []
    entries: list[tuple[str, bool]] = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        match = _KEY_LINE.match(line)
        if not match:
            continue
        name = match.group(1).upper()
        value = match.group(2)
        entries.append((name, not looks_placeholder(value)))
    # Deterministic order: sorted, unique, set-True wins over placeholder.
    merged: dict[str, bool] = {}
    for name, is_set in entries:
        merged[name] = merged.get(name, False) or is_set
    return sorted(merged.items())


def opencode_env_refs(path: Path = Path("opencode.json")) -> list[str]:
    """Extract {env:NAME} references from opencode.json (names only)."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    refs: set[str] = set()

    def _walk(node: object) -> None:
        if isinstance(node, str):
            for m in re.finditer(r"\{env:([A-Za-z_][A-Za-z0-9_]*)\}", node):
                refs.add(m.group(1).upper())
        elif isinstance(node, dict):
            for v in node.values():
                _walk(v)
        elif isinstance(node, list):
            for v in node:
                _walk(v)

    _walk(data)
    return sorted(refs)


def build_report() -> str:
    files = [
        Path(".env"),
        Path(".env.cleaned"),
        Path(".env.example"),
        Path(".env.local"),
        Path(".env.staging.example"),
        Path("open-design/deploy/.env.example"),
    ]
    lines = [
        "# .env key inventory (names only) — 2026-11-08",
        "",
        "Generated by `scripts/security/inventory_env_keys.py`. **No secret values are",
        "printed, logged, or stored** — key names + a boolean `set` flag only.",
        "Surface the `set` column to a human; never paste values into tickets.",
        "",
    ]
    for path in files:
        if not path.exists():
            lines.append(f"## {path} — NOT PRESENT\n")
            continue
        entries = parse_env_file(path)
        lines.append(f"## {path} ({len(entries)} keys)")
        lines.append("")
        lines.append("| Key name | Set |")
        lines.append("|---|---|")
        for name, is_set in entries:
            lines.append(f"| `{name}` | {'yes' if is_set else 'no (placeholder/empty)'} |")
        lines.append("")

    refs = opencode_env_refs()
    lines.append("## opencode.json env references")
    lines.append("")
    lines.append("Names required by `opencode.json` via `{env:NAME}` (names only):")
    lines.append("")
    for name in refs:
        lines.append(f"- `{name}`")
    if not refs:
        lines.append("- _none found (opencode.json missing or no env refs)_")
    lines.append("")
    lines.append("Rotation scope: every key above marked `set` on a non-example file,")
    lines.append("plus the 22-row `credential` table labels and both auth JSONs")
    lines.append("(see `reports/opencode-db-security-fix-2026-11-08.md` §6 and")
    lines.append("`docs/security/CREDENTIAL-ROTATION-RUNBOOK.md`).")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default=None, help="Write report to this path (UTF-8).")
    args = parser.parse_args()
    report = build_report()
    out_path = Path(args.output) if args.output else None
    if out_path:
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(report, encoding="utf-8")
        print(f"Wrote {out_path} ({len(report.splitlines())} lines, names only — no values)")
    else:
        print(report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
